import type { PasswordFieldMap } from '@recoverly/shared-types';
import type { PasswordChangeAdapter } from '../adapter';

/**
 * Google Account Security Password Change Adapter
 * Explicit Policy Note:
 * - Recoverly DOES NOT have direct access to Google Password Manager internal vault.
 * - This adapter navigates to Google Account's public password change endpoint.
 * - The user must log in, complete 2-Step Verification, and confirm the change.
 */
export class GoogleAccountChangePasswordAdapter implements PasswordChangeAdapter {
  public readonly id = 'google';
  public readonly name = 'Google Account Password Change';
  public readonly version = 1;
  public readonly domains = ['google.com', 'accounts.google.com', 'myaccount.google.com'] as const;

  public getChangePasswordUrl(_origin: string): URL | null {
    return new URL('https://myaccount.google.com/signinoptions/password');
  }

  public detectForm(doc: Document): boolean {
    return this.getFieldMap(doc) !== null;
  }

  public getFieldMap(doc: Document): PasswordFieldMap | null {
    const inputs = Array.from(doc.querySelectorAll<HTMLInputElement>('input[type="password"]'));
    if (inputs.length >= 2) {
      // In Google password change, inputs are typically: new password, confirm new password
      const newSel = inputs[0]?.name ? `input[name="${inputs[0].name}"]` : 'input[type="password"]';
      const confirmSel = inputs[1]?.name ? `input[name="${inputs[1].name}"]` : undefined;
      return {
        newPasswordSelector: newSel,
        confirmPasswordSelector: confirmSel,
      };
    }
    return null;
  }

  public detectSuccess(doc: Document): boolean {
    const text = doc.body?.textContent?.toLowerCase() ?? '';
    return text.includes('password changed') || text.includes('password was changed successfully');
  }

  public getManualInstructions(): string[] {
    return [
      'Important: Google does not provide an external API to change passwords directly in Google Password Manager.',
      'Go to Google Account -> Security -> Password (https://myaccount.google.com/signinoptions/password).',
      'Sign in and complete your Google 2-Step Verification prompt.',
      'Enter the new secure password generated by Recoverly into the "New password" and "Confirm new password" fields.',
      'Click "Change Password" to submit the form.',
      'Chrome will automatically detect the change and display a native prompt: "Update password?". Click Update.',
    ];
  }
}
